/// Split a possibly keyed table name into `(tableDocId, contentSubColl)`.
///
/// `getDocumentName`'s `//` folder form yields `<tableDocId>/<subColl>` (single
/// slash), e.g. `84214220504259/report-incident`, targeting a subcollection
/// parallel to `content`. Passing that straight to `.doc()` builds a 5-segment
/// (odd) path → Firestore "Invalid document reference" and wedges historySync.
/// Split so the table-definition doc uses `<tableDocId>` and rows land in the
/// named subcollection. A plain name keeps the default `content` subcollection.
///
/// The boundary is the LAST slash: `getDocumentName` sanitizes the subcoll part
/// to be slash-free, so any remaining slashes belong to a multi-level keyed name
/// (e.g. `$test/report-incident//sub` → `$test/report-incident/sub`). Firestore
/// doc IDs can't contain '/', so collapse them to '%' (getDocumentName's own
/// convention) into one valid segment — otherwise the extra segment lands in the
/// subcoll → 6-segment (even) `.collection()` → "collection path must point to a
/// valid collection".
(String, String) splitKeyedTableName(String tableName, String defaultSub) {
  final int slash = tableName.lastIndexOf('/');
  if (slash < 0) return (tableName, defaultSub);
  final String docId = tableName.substring(0, slash).replaceAll('/', '%');
  return (docId, tableName.substring(slash + 1));
}

